export function normalizeLanguage(value: string | null | undefined): Language {
  return value === 'en' || value === 'en-US' || value?.startsWith('en-') ? 'en-US' : 'zh-CN';
}

export function getInitialLanguage(storage: Storage | null = typeof localStorage === 'undefined' ? null : localStorage, browserLanguage = typeof navigator === 'undefined' ? '' : navigator.language): Language {
  return normalizeLanguage(storage?.getItem(LANGUAGE_STORAGE_KEY) || browserLanguage);
}

export function translate(language: Language, key: string, values: MessageValues = {}): string {
  const template = messages[language][key] || messages['zh-CN'][key] || key;
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values[name] ?? `{{${name}}}`));
}

type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: MessageValues) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => getInitialLanguage());
  useEffect(() => { localStorage.setItem(LANGUAGE_STORAGE_KEY, language); }, [language]);
  const value = useMemo(() => ({ language, setLanguage, t: (key: string, values?: MessageValues) => translate(language, key, values) }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}

export function LanguageSwitcher() {
  const { language, setLanguage, t } = useI18n();
  const next = language === 'zh-CN' ? 'en-US' : 'zh-CN';
  return (
    <button type="button" className="soft language-toggle" onClick={() => setLanguage(next)} aria-label={t('language.switchTo')} title={t('language.switchTo')}>
      {t('language.button')}
    </button>
  );
}
